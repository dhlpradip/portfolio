/** Drop-in point for Firestore — swap the return below when backend is wired. */
export async function getWritings(): Promise<Writing[]> {
  // FUTURE:
  // const snapshot = await db.collection("writings").where("published", "==", true)...
  // return snapshot.docs.map(doc => doc.data() as Writing);

  return staticWritings
    .filter((w) => w.published)
    .sort(
      (a, b) =>
        new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
    );
}

export async function getWritingBySlug(
  slug: string
): Promise<Writing | undefined> {
  // FUTURE: const doc = await db.collection("writings").where("slug", "==", slug).limit(1).get()

  const writing = staticWritings.find((w) => w.slug === slug && w.published);
  return writing;
}

export async function getWritingSlugs(): Promise<string[]> {
  const writings = await getWritings();
  return writings.map((w) => w.slug);
}
